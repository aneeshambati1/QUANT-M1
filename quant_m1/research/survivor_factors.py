"""Survivor factor integration for QUANT-M1.

Uses pre-built LS portfolio returns from Open Asset Pricing (Chen & Zimmermann)
as research reference signals. These are NOT directly tradeable — they represent
academic long-short factor portfolios on CRSP universe.

Integration path:
1. Load survivor_factors.csv (generated by battery script)
2. Use factor returns as regime-aware signal inputs to meta-selector
3. Map factor exposures to tradeable ETF proxies where possible
4. Apply cost-aware allocation with Risk Kernel veto

This module does NOT route orders, grant authority, or enable Phase 2.
"""
from __future__ import annotations
import math
from typing import Dict, Optional
import numpy as np
import pandas as pd


FACTOR_FAMILIES = {
    "options_informed": ["SmileSlope", "dCPVolSpread", "CPVolSpread"],
    "earnings_events": ["AnnouncementReturn", "EarningsStreak", "ChangeInRecommendation"],
    "short_volume": ["ShortInterest", "VolumeTrend"],
    "external_financing": ["NetDebtFinance", "ShareIss1Y", "ShareIss5Y", "XFIN"],
    "industry_momentum": ["IndRetBig"],
    "seasonality": ["MomSeason16YrPlus"],
    "revenue_surprise": ["RevenueSurprise"],
    "tax_accruals": ["ChTax"],
    "short_reversal": ["REV6"],
}

REGIME_FAMILY_WEIGHTS = {
    "calm": {
        "earnings_events": 0.30, "external_financing": 0.25,
        "short_volume": 0.20, "industry_momentum": 0.15,
        "options_informed": 0.10,
    },
    "elevated": {
        "earnings_events": 0.25, "external_financing": 0.30,
        "short_volume": 0.25, "industry_momentum": 0.10,
        "options_informed": 0.10,
    },
    "risk_off": {
        "external_financing": 0.35, "short_volume": 0.30,
        "earnings_events": 0.20, "industry_momentum": 0.10,
        "options_informed": 0.05,
    },
    "crisis": {
        "external_financing": 0.40, "short_volume": 0.35,
        "earnings_events": 0.15, "industry_momentum": 0.05,
        "options_informed": 0.05,
    },
    "unknown": {
        "earnings_events": 0.25, "external_financing": 0.25,
        "short_volume": 0.25, "industry_momentum": 0.15,
        "options_informed": 0.10,
    },
}


def load_survivor_factors(path: str = "evidence/survivor_factors.csv") -> pd.DataFrame:
    """Load pre-computed survivor factor returns."""
    df = pd.read_csv(path, index_col=0, parse_dates=True)
    return df.sort_index()


def compute_factor_signals(factors: pd.DataFrame, lookback: int = 12) -> Dict[str, float]:
    """Compute trailing factor momentum/strength signals.

    For each factor, compute the trailing 12-month cumulative return.
    Positive = factor is working recently; negative = factor is out of favor.
    This is a META-signal: which factors are currently effective.
    """
    if len(factors) < lookback:
        return {col: 0.0 for col in factors.columns}
    recent = factors.iloc[-lookback:]
    signals = {}
    for col in factors.columns:
        r = recent[col].dropna()
        if len(r) < 6:
            signals[col] = 0.0
        else:
            cum = float(np.prod(1.0 + r.values) - 1.0)
            signals[col] = cum
    return signals


def select_family_weights(regime: str) -> Dict[str, float]:
    """Get pre-registered family weights for a regime."""
    return dict(REGIME_FAMILY_WEIGHTS.get(regime, REGIME_FAMILY_WEIGHTS["unknown"]))


def blend_factor_signals(signals: Dict[str, float], regime: str) -> Dict[str, float]:
    """Blend individual factor signals into family-level scores."""
    family_weights = select_family_weights(regime)
    family_scores = {}
    for family, members in FACTOR_FAMILIES.items():
        member_signals = [signals.get(m, 0.0) for m in members if m in signals]
        if not member_signals:
            family_scores[family] = 0.0
            continue
        avg_signal = float(np.mean(member_signals))
        weight = family_weights.get(family, 0.0)
        family_scores[family] = avg_signal * weight
    return family_scores


def rank_families(family_scores: Dict[str, float]) -> list:
    """Rank families by blended score, descending."""
    return sorted(family_scores.items(), key=lambda x: x[1], reverse=True)


def factor_integration_report(factors: pd.DataFrame, regime: str = "unknown") -> dict:
    """Generate a research report on current factor effectiveness."""
    signals = compute_factor_signals(factors)
    family_scores = blend_factor_signals(signals, regime)
    ranked = rank_families(family_scores)

    return {
        "regime": regime,
        "n_factors": len(factors.columns),
        "n_months": len(factors),
        "factor_signals": signals,
        "family_scores": family_scores,
        "ranked_families": [{"family": f, "score": s} for f, s in ranked],
        "live_trading": False,
        "grants_authority": False,
        "phase2_enabled": False,
        "disclosure": "Research reference only. Pre-built academic LS portfolios. Not directly tradeable.",
    }
